<?php

declare(strict_types=1);

namespace ForumKit\Forums\Models;

use ForumKit\Core\Support\Tables;
use ForumKit\Core\Support\UserModel;
use ForumKit\Forums\Enums\ContentModerationStatus;
use ForumKit\Forums\Support\Models;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;

/**
 * @property int $id
 * @property int $forum_id
 * @property int $author_id
 * @property string $title
 * @property string $slug
 * @property ContentModerationStatus $moderation_status
 * @property bool $is_pinned
 * @property bool $is_locked
 * @property int $reply_count
 * @property int $view_count
 * @property int|null $last_post_author_id
 * @property Carbon|null $last_post_at
 * @property int|null $approved_by_id
 * @property Carbon|null $approved_at
 * @property int|null $rejected_by_id
 * @property Carbon|null $rejected_at
 * @property string|null $moderation_reason
 * @property Carbon|null $last_activity_at Generated by the database; read-only.
 */
class Thread extends Model
{
    protected $fillable = [
        'forum_id',
        'author_id',
        'title',
        'slug',
        'moderation_status',
        'is_pinned',
        'is_locked',
        'reply_count',
        'view_count',
        'last_post_author_id',
        'last_post_at',
        'approved_by_id',
        'approved_at',
        'rejected_by_id',
        'rejected_at',
        'moderation_reason',
    ];

    public function getTable(): string
    {
        return Tables::name('threads');
    }

    protected function casts(): array
    {
        return [
            'is_pinned' => 'boolean',
            'is_locked' => 'boolean',
            'moderation_status' => ContentModerationStatus::class,
            'last_post_at' => 'datetime',
            // Generated in the schema from last_post_at and created_at; read-only, and
            // deliberately absent from $fillable.
            'last_activity_at' => 'datetime',
            'approved_at' => 'datetime',
            'rejected_at' => 'datetime',
        ];
    }

    /**
     * @return BelongsTo<Model, $this>
     */
    public function forum(): BelongsTo
    {
        return $this->belongsTo(Models::class('forum'), 'forum_id');
    }

    /**
     * @return BelongsTo<Model, $this>
     */
    public function author(): BelongsTo
    {
        return $this->belongsTo(UserModel::class(), 'author_id');
    }

    /**
     * @return BelongsTo<Model, $this>
     */
    public function lastPostAuthor(): BelongsTo
    {
        return $this->belongsTo(UserModel::class(), 'last_post_author_id');
    }

    /**
     * @return BelongsTo<Model, $this>
     */
    public function approvedBy(): BelongsTo
    {
        return $this->belongsTo(UserModel::class(), 'approved_by_id');
    }

    /**
     * @return BelongsTo<Model, $this>
     */
    public function rejectedBy(): BelongsTo
    {
        return $this->belongsTo(UserModel::class(), 'rejected_by_id');
    }

    /**
     * @return HasMany<Model, $this>
     */
    public function posts(): HasMany
    {
        return $this->hasMany(Models::class('post'), 'thread_id');
    }

    /**
     * @return HasMany<Model, $this>
     */
    public function reports(): HasMany
    {
        return $this->hasMany(Models::class('post_report'), 'thread_id');
    }

    /**
     * @return HasMany<Model, $this>
     */
    public function moderationLogs(): HasMany
    {
        return $this->hasMany(Models::class('thread_moderation_log'), 'thread_id');
    }

    /**
     * @param  Builder<self>  $query
     * @return Builder<self>
     */
    public function scopeApproved(Builder $query): Builder
    {
        return $query->where('moderation_status', ContentModerationStatus::APPROVED->value);
    }

    public function isApproved(): bool
    {
        return $this->moderation_status === ContentModerationStatus::APPROVED;
    }

    public function isPending(): bool
    {
        return $this->moderation_status === ContentModerationStatus::PENDING;
    }

    public function isRejected(): bool
    {
        return in_array($this->moderation_status, [ContentModerationStatus::REJECTED, ContentModerationStatus::REJECTED_FINAL], true);
    }
}
